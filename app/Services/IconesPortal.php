    /** O SVG do ícone, ou '' se o nome não existe. */
    public static function svg(string $nome, string $classe = ''): string
    {
        if (!isset(self::DESENHOS[$nome])) {
            return '';
        }
        return '<svg class="ic' . ($classe !== '' ? ' ' . $classe : '') . '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
            . self::DESENHOS[$nome] . '</svg>';
    }

    /** nome => SVG, para o JavaScript do portal (BOOT.ic). @param array<int, string> $nomes @return array<string, string> */
    public static function conjunto(array $nomes): array
    {
        $saida = [];
        foreach ($nomes as $nome) {
            $saida[$nome] = self::svg($nome);
        }
        return $saida;
